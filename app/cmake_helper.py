# cmake_helper.py
#
# Helper to run a CMake build from pytest tests.
#
# Use it from a test by importing it:
#     from cmake_helper import cmake_build

import subprocess


__tracebackhide__ = True

_REPORTED_LINES = 20


def cmake_build(build_dir, build_target, clean=False):
    """Build ``build_target`` using CMake.

    ``build_dir`` is the directory where the build files are located (generated by CMake configure step).
    ``build_target`` is the name of the target to build (defined in the CMakeLists.txt with add_executable).
    If ``clean`` is set to True, the build will be cleaned (--clean-first) before building the target.
    """
    args = ["cmake", "--build", build_dir, "--target", build_target]
    if clean:
        args.append("--clean-first")

    print(f"\nCompiling target {build_target}")
    result = subprocess.run(args, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if result.returncode != 0:
        lines = result.stdout.splitlines()
        if len(lines) > _REPORTED_LINES:
            print(result.stdout)
        raise RuntimeError(_failure_message(build_target, result.returncode, lines))


def _failure_message(build_target, returncode, lines):
    message = [f"Build of target '{build_target}' failed with exit code {returncode}."]
    if not lines:
        message.append("The build produced no output.")
        return "\n".join(message)

    if len(lines) > _REPORTED_LINES:
        message.append(f"Last {_REPORTED_LINES} of {len(lines)} output lines (full log above):")
    else:
        message.append("Build output:")
    message += [f"  {line}" for line in lines[-_REPORTED_LINES:]]
    return "\n".join(message)
